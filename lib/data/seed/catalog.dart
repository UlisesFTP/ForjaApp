/// Looks an exercise up by id; an unknown id yields an archived placeholder so
/// history that references it keeps rendering.
Exercise exerciseFor(String id) {
  for (final e in exerciseCatalog) {
    if (e.id == id) return e;
  }
  return Exercise.archived(id);
}

PlanExercise _planned(String id) => PlanExercise.fromExercise(exerciseFor(id));

